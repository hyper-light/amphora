#!/usr/bin/env python3
"""Lift flex's tables for PostgreSQL 19's scan.l into Rust constants (docs/design/postgres.md
section 3; section 11's unit 4). Reads the scan.c that `flex -CF -p -p -b` (PostgreSQL's flags,
src/backend/parser/Makefile) writes, and prints crates/pg-parser/src/scan_tables.rs.

usage: postgres-tables.py <scan.c> <flex version> <sha256 of scan.l>"""
import re
import sys


def table(src: str, name: str) -> str:
    m = re.search(r"static const [^\n]*\b" + name + r"\[(\d+)\] =\s*\{(.*?)\}\s*;", src, re.S)
    if not m:
        sys.exit(f"{name} not found")
    return m.group(1), m.group(2)


def main() -> None:
    path, version, digest = sys.argv[1:4]
    src = open(path, encoding="utf-8").read()
    n, body = table(src, "yy_transition")
    pairs = [(int(v), int(x)) for v, x in re.findall(r"\{\s*(-?\d+),\s*(-?\d+)\s*\}", body)]
    if len(pairs) > int(n):
        sys.exit(f"yy_transition: {len(pairs)} entries, declared {n}")
    # flex declares more entries than it writes; C zero-fills the rest (C11 6.7.9p21).
    pairs += [(0, 0)] * (int(n) - len(pairs))
    sn, sbody = table(src, r"\*yy_start_state_list")
    starts = [int(i) for i in re.findall(r"&yy_transition\[(\d+)\]", sbody)]
    if len(starts) != int(sn):
        sys.exit(f"yy_start_state_list: {len(starts)} entries, declared {sn}")
    rules = int(re.search(r"#define YY_NUM_RULES (\d+)", src).group(1))
    eob = int(re.search(r"#define YY_END_OF_BUFFER (\d+)", src).group(1))
    conds = re.findall(r"^#define (INITIAL|x[a-z]+) (\d+)$", src, re.M)
    verify_max = max(v for v, _ in pairs)
    out = [
        f"//! flex {version}'s tables for vendor/postgres/src/backend/parser/scan.l (sha256 {digest}),",
        "//! generated by scripts/postgres-tables.sh with PostgreSQL's flags `-CF -p -p` and no backing up.",
        "//! Not edited by hand: regenerate.",
        "",
        f"pub const SCAN_L_SHA256: &str = \"{digest}\";",
        f"/// scan.l's rules; flex numbers its end-of-buffer action {eob}.",
        f"pub const RULES: u16 = {rules};",
        f"pub const END_OF_BUFFER: u16 = {eob};",
        "/// Start conditions, as scan.l declares them (`BEGIN(c)` starts at `START[1 + 2 * c]`).",
    ]
    for name, num in conds:
        out.append(f"pub const {name.upper()}: usize = {num};")
    out.append(f"pub static START: [u32; {len(starts)}] = {starts};")
    out.append(f"/// yy_transition's yy_verify: the input byte a transition is for (up to {verify_max}).")
    out.append(f"pub static VERIFY: [u16; {len(pairs)}] = [{', '.join(str(v) for v, _ in pairs)}];")
    out.append("/// yy_transition's yy_nxt: the step to the next state, or in a state's slot -1 its action.")
    out.append(f"pub static NEXT: [i32; {len(pairs)}] = [{', '.join(str(x) for _, x in pairs)}];")
    print("\n".join(out))


main()
