#!/usr/bin/env python3
"""gram.h's token numbers and kwlist.h's keyword table for the scanner (docs/design/postgres.md
section 3; section 11's unit 4), as Rust constants. bison numbers a grammar's named tokens from 258
in the order gram.y's declarations first name them; the oracle's --tokens output checks the result.

usage: postgres-tokens.py <gram.y> <kwlist.h>  (prints crates/pg-parser/src/scan_tokens.rs)"""
import re
import sys


def main() -> None:
    gram, kwlist = sys.argv[1:3]
    decls = open(gram, encoding="utf-8").read().split("\n%%\n", 1)[0]
    decls = re.sub(r"/\*.*?\*/", " ", decls, flags=re.S)
    names = []
    for m in re.finditer(r"^%(token|left|right|nonassoc|precedence)\b([^%]*)", decls, re.M):
        for word in re.sub(r"<[^>]*>", " ", m.group(2)).split():
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", word) and word not in names:
                names.append(word)
    keywords = re.findall(r'^PG_KEYWORD\("([a-z_]+)", ([A-Z_0-9]+), ', open(kwlist, encoding="utf-8").read(), re.M)
    if [k for k, _ in keywords] != sorted(k for k, _ in keywords):
        sys.exit("kwlist.h is not sorted")
    number = {name: 258 + i for i, name in enumerate(names)}
    out = [
        "//! gram.h's token numbers (bison 3.8's numbering of vendor/postgres/src/backend/parser/gram.y's",
        "//! declarations) and kwlist.h's keywords, generated by scripts/postgres-tokens.py. Not edited by hand.",
        "",
    ]
    for name in names:
        out.append(f"pub const {name.upper()}: i32 = {number[name]};")
    out.append("/// kwlist.h's keywords, sorted by name, each with its token.")
    out.append(f"pub static KEYWORDS: [(&str, i32); {len(keywords)}] = [")
    for k, tok in keywords:
        out.append(f"    (\"{k}\", {tok.upper()}),")
    out.append("];")
    print("\n".join(out))


main()
