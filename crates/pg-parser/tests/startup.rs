/// T-PG.6.5: each statement parses to the oracle's tree.
#[test]
fn t_pg_6_5_driver_startup_statements_parse_to_19s_trees() {
    for (sql, oracle) in STARTUP {
        let (tree, statements) =
            gram::parse(sql.as_bytes()).unwrap_or_else(|e| panic!("{sql}: {e:?}"));
        assert_eq!(&tree.to_text(&statements).unwrap(), oracle, "{sql}");
    }
}
