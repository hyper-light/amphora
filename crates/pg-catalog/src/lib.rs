/// A session's effective search path: the schemas an unqualified name is looked up in, in order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SearchPath {
    namespaces: Vec<u32>,
    temp: Option<u32>,
}

impl SearchPath {
    /// The path 19 searches for `search_path`'s entries (already split into names, as
    /// `SplitIdentifierString` splits them), for a session whose role is `role` and whose temporary
    /// schema, once it has one, is `temp`. `namespace` finds a schema's OID by name.
    ///
    /// `preprocessNamespacePath` (src/backend/catalog/namespace.c:4179-4268): `$user` is the schema
    /// named after the role, if one exists; `pg_temp` is the temporary schema, if the session has
    /// one; a name that names no schema is skipped. `finalNamespacePath` (`:4277-4320`): repeats are
    /// dropped, then `pg_catalog` goes first unless it was listed, then the temporary schema before
    /// it unless it was listed. Schema privileges are not modelled yet: every schema is usable.
    pub fn new(
        entries: &[&str],
        role: &str,
        temp: Option<u32>,
        namespace: impl Fn(&str) -> Option<u32>,
    ) -> Self {
        let mut namespaces: Vec<u32> = Vec::with_capacity(entries.len().saturating_add(2));
        for entry in entries {
            let oid = match *entry {
                "$user" => namespace(role),
                "pg_temp" => temp,
                name => namespace(name),
            };
            if let Some(oid) = oid
                && !namespaces.contains(&oid)
            {
                namespaces.push(oid);
            }
        }
        if !namespaces.contains(&PG_CATALOG_NAMESPACE) {
            namespaces.insert(0, PG_CATALOG_NAMESPACE);
        }
        if let Some(temp) = temp
            && !namespaces.contains(&temp)
        {
            namespaces.insert(0, temp);
        }
        Self { namespaces, temp }
    }

    /// The schemas searched for a name of `kind`, in order: the temporary schema is skipped for
    /// functions (`FuncnameGetCandidates`, namespace.c:1268-1276; the same for operators), and
    /// searched for relations (`RelnameGetRelid`, `:886`) and types (`TypenameGetTypidExtended`
    /// with `temp_ok`, `:1009-1021`, which `LookupTypeName` passes as true,
    /// src/backend/parser/parse_type.c:38-43).
    pub fn namespaces(&self, kind: Kind) -> impl Iterator<Item = u32> + '_ {
        let skip = if kind == Kind::Function {
            self.temp
        } else {
            None
        };
        self.namespaces
            .iter()
            .copied()
            .filter(move |ns| Some(*ns) != skip)
    }

    /// The object an unqualified relation or type name resolves to: the first schema on the path
    /// holding the name wins. `find` looks the name up in one schema.
    pub fn resolve<T>(&self, kind: Kind, mut find: impl FnMut(u32) -> Option<T>) -> Option<T> {
        self.namespaces(kind).find_map(&mut find)
    }

    /// The functions an unqualified name can call, as `FuncnameGetCandidates` collects them
    /// (namespace.c:1199-1400): every function of that name in a schema on the path, where one in
    /// an earlier schema hides one with the same argument types in a later schema.
    pub fn function_candidates<'a, F>(&self, name: &str, functions: F) -> Vec<&'a Proc>
    where
        F: IntoIterator<Item = &'a Proc>,
    {
        let mut ranked: Vec<(usize, &'a Proc)> = functions
            .into_iter()
            .filter(|p| p.name == name)
            .filter_map(|p| {
                self.namespaces(Kind::Function)
                    .position(|ns| ns == p.namespace)
                    .map(|pos| (pos, p))
            })
            .collect();
        ranked.sort_by_key(|(pos, p)| (*pos, p.oid));
        let mut visible: Vec<&'a Proc> = Vec::with_capacity(ranked.len());
        for (_, p) in ranked {
            if !visible.iter().any(|v| v.args == p.args) {
                visible.push(p);
            }
        }
        visible
    }
}

